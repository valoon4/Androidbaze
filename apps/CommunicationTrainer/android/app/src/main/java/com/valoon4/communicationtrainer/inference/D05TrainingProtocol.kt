package com.valoon4.communicationtrainer.inference

import org.json.JSONArray
import org.json.JSONObject

/** Public, fixed training material. No contact with Room or D03 messages. */
enum class D05Scenario(
    val displayName: String,
    val description: String,
    val opening: String,
    val instructions: String
) {
    WORKLOAD(
        "Eine Bitte freundlich ablehnen",
        "Eine Kollegin bittet dich kurz vor Feierabend, zusätzliche Aufgaben zu übernehmen.",
        "Hast du noch zehn Minuten? Könntest du meine Aufgabe heute übernehmen? Ich schaffe das sonst nicht.",
        "Du spielst Lena, eine fiktive Kollegin. Sie bittet kurz vor Feierabend um Unterstützung, ist leicht gestresst und reagiert glaubwürdig auf Grenzen. " +
            "Bleibe in der Rolle und antworte mit höchstens zwei kurzen deutschen Sätzen. " +
            "Widersprich bei Bedarf höflich, aber respektiere eine klare Grenze spätestens nach der zweiten Erklärung. " +
            "Kein Coaching, keine Bewertung, kein Diagnostizieren, keine Aufforderung zu privaten Daten."
    ),
    CANCELLATION(
        "Ein schwieriges Gespräch führen",
        "Ein guter Freund fühlt sich zurückgesetzt, weil du eine Verabredung abgesagt hast.",
        "Du hast schon wieder abgesagt. Ich habe das Gefühl, unsere Freundschaft ist dir nicht mehr wichtig.",
        "Du spielst Alex, einen fiktiven Freund, der nach einer kurzfristigen Absage enttäuscht ist. " +
            "Reagiere auf den Inhalt der vorherigen Aussage, nicht mit standardisierten Floskeln. " +
            "Bleibe glaubwürdig und fair, höchstens zwei kurze deutsche Sätze je Antwort. " +
            "Keine Therapie, keine Diagnosen, keine privaten Daten erfragen. Eine empathische Klärung soll möglich sein."
    )
}

data class D05Turn(val role: String, val text: String)

/**
 * ChatGPT-plan preview requires full input context in every request.
 * Explicitly do NOT use previous_response_id, conversation IDs or hidden
 * server-side history. Only turns from this *new* in-memory exercise are used.
 */
object D05TrainingProtocol {
    const val MAX_MESSAGES = 5
    const val MAX_USER_CHARS = 500
    const val MAX_BOT_CHARS = 1600
    const val MAX_INPUT_BYTES = 30_000
    const val MAX_STREAM_BYTES = 1_048_576
    const val MAX_SSE_EVENT_BYTES = 16_384
    val SLUG_PATTERN = Regex("^[a-zA-Z0-9][a-zA-Z0-9._-]{1,127}$")

    fun validUserMessage(text: String): Boolean =
        text.isNotBlank() && text.length <= MAX_USER_CHARS && text.none { it == '\u0000' }

    fun requestBody(
        modelSlug: String,
        scenario: D05Scenario,
        completedHistory: List<D05Turn>,
        latestUserText: String
    ): JSONObject {
        require(SLUG_PATTERN.matches(modelSlug)) { "Unzulässiges Modell." }
        require(validUserMessage(latestUserText)) { "Nachricht nicht gültig." }
        require(completedHistory.size % 2 == 0 && completedHistory.size <= 2 * (MAX_MESSAGES - 1))
        for (i in completedHistory.indices) {
            val turn = completedHistory[i]
            require(turn.role == if (i % 2 == 0) "user" else "assistant")
            require(turn.text.isNotBlank() && turn.text.length <=
                if (turn.role == "user") MAX_USER_CHARS else MAX_BOT_CHARS)
        }
        val input = JSONArray()
        // The opening remains part of instructions, not an invented assistant
        // completion: the actual first assistant turn is generated by the API.
        input.put(JSONObject().put("role", "user").put("content",
            "TRAININGSKONTEXT (nur fiktiv): " + scenario.opening))
        for (turn in completedHistory) {
            input.put(JSONObject().put("role", turn.role).put("content", turn.text))
        }
        input.put(JSONObject().put("role", "user").put("content", latestUserText))
        val body = JSONObject()
            .put("model", modelSlug)
            .put("instructions", scenario.instructions)
            .put("input", input)
            .put("store", false)
            .put("stream", true)
        require(body.toString().toByteArray(Charsets.UTF_8).size <= MAX_INPUT_BYTES)
        return body
    }
}
