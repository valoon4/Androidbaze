'use strict';
const assert=require('node:assert/strict');
const n=require('../network.js');
const p={name:'A',dims:{w:2400,d:1900,h:2100},walls:[{id:'SW1',holes:[]}],
 cables:[{id:'C1',name:'Rot',group:'OLA',a:{wall:'SW1',hole:'H1'},b:null}]};
let net=n.createNetwork(p);
assert.equal(net.shafts[0].id,'S1');
net.shafts.push({id:'S2',name:'Zwei',x:6000,z:3000,snapshot:n.snapshot({...p,name:'Zwei',cables:[{...p.cables[0],id:'C2'}]})});
net.links.push({id:'L1',from:'S1',to:'S2',note:'Rohrbrücke'});
net.routes.push({id:'R1',name:'Haupttrasse',group:'OLA',steps:[{shaftId:'S1',cableId:'C1'},{shaftId:'S2',cableId:'C2'}]});
const valid=n.normalizeNetwork(net,p);
assert.equal(valid.shafts.length,2);
assert.deepEqual(n.issues(valid,valid.routes[0]),[]);
assert.equal(n.routeDetails(valid,valid.routes[0])[1].cableId,'C2');
assert.equal(n.routeDetails(valid,valid.routes[0])[0].from,'SW1 / H1');
assert.ok(n.inventoryCSV(valid).includes('Haupttrasse')===false);
assert.ok(n.inventoryCSV(valid).includes('Schacht-ID'));
const pImport=n.parsePositionsCSV('shaft_id;x_mm;z_mm\nS1;1500;-700\nS2;8000;9000\n',valid);
assert.deepEqual(pImport.warnings,[]);
assert.equal(n.applyPositions(valid,pImport.rows).shafts[1].x,8000);
assert.equal(valid.shafts[1].x,6000);
const bad=n.parsePositionsCSV('shaft_id;x_mm;z_mm\nS9;1;2\nS1;abc;4\nS2;5;6\n',valid);
assert.equal(bad.rows.length,1);
assert.equal(bad.warnings.length,2);
const dup=n.normalizeNetwork({...net,links:[net.links[0],{id:'L2',from:'S2',to:'S1'}]},p);
assert.equal(dup.links.length,1);
const broken=n.normalizeNetwork({...net,links:[]},p);
assert.ok(n.issues(broken,broken.routes[0]).some(x=>x.includes('Keine Netzverbindung')));
const missing=n.normalizeNetwork({...net,routes:[{...net.routes[0],steps:[{shaftId:'S1',cableId:'BOGUS'}]}]},p);
assert.ok(n.issues(missing,missing.routes[0]).length>0);
assert.ok(!('network' in n.snapshot({...p,network:net})));
console.log('OK: Netzgraph, IDs, Links, Kabelverfolgung, CSV Import/Export, unvollständige Wege');
