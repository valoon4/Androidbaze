'use strict';
const assert=require('node:assert/strict');
const M=require('../app/src/main/assets/session-math.js');
const utc=(h,m=0,day=1)=>new Date(2026,0,day,h,m).getTime();
function get(a,field,value){let r=M.update(a,field,value);assert.ok(r.value,r.error);return r.value;}
let original={start:utc(10),end:utc(12),pauseMs:0,workMs:7200000};
assert.equal(M.formatDuration(M.parseDuration('1:30')),'01:30:00');
assert.equal(M.formatDuration(M.parseDuration('1:30:15')),'01:30:15');
assert.equal(M.formatDuration(M.parseDuration('90')),'01:30:00');
assert.equal(M.parseDuration('1:99'),null);
assert.equal(M.parseDuration('-1'),null);
assert.equal(get(original,'workMs',10800000).end,utc(13));
assert.equal(get(original,'end',utc(14,30)).workMs,16200000);
assert.equal(get(original,'start',utc(9)).end,utc(11));
assert.equal(get({...original,end:utc(13),workMs:10800000},'pauseMs',45*60000).workMs,135*60000);
let night=get({start:utc(22),end:utc(23),workMs:3600000,pauseMs:0},'end',utc(2,0,2));
assert.equal(night.workMs,14400000);
assert.equal(Object.values(M.dayBreakdown({...night,workMs:14400000})).reduce((a,b)=>a+b,0),14400000);
let tracked={start:utc(9),end:utc(12),status:'done',segments:[{start:utc(9),end:utc(10)},{start:utc(10,30),end:utc(12)}]};
assert.equal(M.workMs(tracked),9000000);
assert.equal(M.pauseMs(tracked),1800000);
let edit=get(M.initial(tracked),'workMs',10800000);
assert.equal(edit.end,utc(12,30));
assert.equal(edit.pauseMs,1800000);
assert.ok(M.update(original,'pauseMs',7200001).error);
assert.ok(M.update(original,'end',utc(9)).error);
assert.equal(M.workMs({...tracked,workMs:10800000}),10800000);
assert.equal(M.pauseMs({...tracked,workMs:10800000,pauseMs:1800000}),1800000);
let cross={start:utc(23,30),end:utc(0,30,2),workMs:1800000,pauseMs:1800000};
let parts=M.dayBreakdown(cross);
assert.equal(Object.values(parts).reduce((a,b)=>a+b,0),1800000);
assert.equal(Object.keys(parts).length,2);
const json=JSON.stringify({projects:[{id:'p'}],tasks:[{id:'t',projectId:'p'}],sessions:[{...tracked,workMs:edit.workMs,pauseMs:edit.pauseMs,start:edit.start,end:edit.end}]});
assert.equal(JSON.parse(json).sessions[0].workMs,10800000);
console.log('PASS: TimeFlow 1.1 session calculations, pauses, midnight, compatibility, serialization');
